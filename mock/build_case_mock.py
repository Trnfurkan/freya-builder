"""Build the case's mock (Cloudflare Worker) and its tool API file from the case's own documents.

    python mock/build_case_mock.py <case folder> [--out mock/case]

Reads <case folder>/test-environment/test-customers.json (the bank's exact answers per test customer) and writes:
  <out>/worker.js       the Worker: the contract's paths (POST /voice/v1/<service>), the listed answer and HTTP status
                        for every test customer, card and week, the contract's 404/400 for anything not listed,
                        `delaySeconds` waits, CORS, GET /health and GET /__records.
  <out>/wrangler.toml   for `npx wrangler deploy` (the dashboard paste needs only worker.js).
  <out>/openapi.json    the tool API file for the builder: the same seven services, nested data/call bodies.
The routes, field names, error codes and lookups below are the ones in the case's service contract (section 4-6) and
test-environment/test-customers.md; the data is never edited.
"""
import argparse
import json
import pathlib

SERVICES = {
    # service: (lookup fields in data, 404 code for "not listed" or None, required fields with their 400 message)
    "cards.list": (["customerNo"], ("FB_IVR_CHANNEL_102", "Müşteriye ait geçerli kart bilgisi bulunamadı."),
                   {"customerNo": "customer number cannot be empty"}),
    "cards.balance": (["cardNumber"], ("FB_IVR_CHANNEL_120", "Kart bakiye servisi hatası: kart bulunamadı"),
                      {"cardNumber": "card number cannot be empty"}),
    "statement.week.get": (["cardNumber"], ("FB_IVR_CHANNEL_121", "Kart bulunamadı"),
                           {"cardNumber": "card number cannot be empty"}),
    "statement.week.decide": (["cardNumber", "newStatementWeek"], None,
                              {"cardNumber": "card number cannot be empty",
                               "newStatementWeek": "newStatementWeek cannot be empty"}),
    "statement.week.change": (["cardNumber", "newStatementWeek"], None,
                              {"cardNumber": "card number cannot be empty",
                               "newStatementWeek": "newStatementWeek cannot be empty"}),
    "contact.email.get": (["customerNo"], None, {"customerNo": "customer number cannot be empty",
                                                 "intAddressInfoType": "intAddressInfoType cannot be empty"}),
    "statement.pdf.send": (["customerNo"], ("FB_IVR_CHANNEL_107", "Pdf dokümanı bulunamadı"),
                           {"customerNo": "customer number cannot be empty"}),
}

WORKER = r"""// Freya Bank statement-debt services: the team's mock, generated by mock/build_case_mock.py from the case's
// test-environment/test-customers.json and service contract. Do not edit by hand; run the generator again.
const BASE = "/voice/v1/";
const SERVICES = __SERVICES__;
const DATA = __DATA__;

const CORS = { "Access-Control-Allow-Origin": "*" };
const records = [];

function hex32() {
  const a = new Uint8Array(16);
  crypto.getRandomValues(a);
  return Array.from(a, (b) => b.toString(16).padStart(2, "0")).join("");
}

function errorBody(code, message, type, rootCause) {
  const guid = hex32();
  return { result: { guid, returnCode: code, messageText: message, code, message, type,
                     details: { guid, rootCause, errorOrigin: "ivr-gateway-test:ivr-channel-v0" } } };
}

function send(status, body) {
  return new Response(JSON.stringify(body), { status, headers: { ...CORS, "content-type": "application/json; charset=utf-8" } });
}

function isTemplate(v) {
  return typeof v === "string" && (v.startsWith("{{") || v.startsWith("%7B%7B"));
}

function key(v) {
  return v === undefined || v === null ? "" : String(v).trim();
}

// The answer listed for this request, or null. Lookups as in test-customers.md.
function lookup(service, data) {
  const table = DATA[service] || {};
  const [first, second] = SERVICES[service].lookup;
  const hit = table[key(data[first])];
  if (!hit) return null;
  if (!second) return hit;
  return hit[key(data[second])] || null;
}

async function handle(service, request) {
  let body = {};
  try { body = await request.json(); } catch (e) { body = {}; }
  const data = body && typeof body.data === "object" && body.data ? body.data : {};
  const spec = SERVICES[service];
  // The dashboard's "Test API Request" sends {{variables}} unfilled: answer as for the first test customer.
  if (Object.values(data).some(isTemplate)) {
    const sample = DATA.__sample__[service];
    if (sample) return [sample.http, sample.response];
  }
  for (const [field, message] of Object.entries(spec.required)) {
    if (key(data[field]) === "") return [400, errorBody("INVALID_ARGUMENTS_ERROR", message, "ERROR", "InvalidArgumentsException")];
  }
  const hit = lookup(service, data);
  if (hit) {
    if (hit.delaySeconds) await new Promise((r) => setTimeout(r, Number(hit.delaySeconds) * 1000));
    return [hit.http, hit.response];
  }
  if (spec.notFound) return [404, errorBody(spec.notFound[0], spec.notFound[1], "WARNING", "NotFoundException")];
  return [400, errorBody("INVALID_ARGUMENTS_ERROR", "no test record for this request", "ERROR", "InvalidArgumentsException")];
}

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method === "OPTIONS") {
      return new Response(null, { headers: { ...CORS, "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
                                             "Access-Control-Allow-Headers": "*" } });
    }
    if (request.method === "GET" && url.pathname === "/health") return send(200, { status: "ok", services: Object.keys(SERVICES) });
    if (request.method === "GET" && url.pathname === "/__records") return send(200, { calls: records });
    const service = url.pathname.startsWith(BASE) ? url.pathname.slice(BASE.length).replace(/\/+$/, "") : "";
    if (request.method !== "POST" || !SERVICES[service]) {
      return send(404, errorBody("NOT_FOUND", "unknown path " + request.method + " " + url.pathname, "ERROR", "NotFound"));
    }
    const copy = request.clone();
    const [status, body] = await handle(service, request);
    let data = null;
    try { data = (await copy.json()).data; } catch (e) { data = null; }
    records.push({ at: new Date().toISOString(), service, data, status });
    if (records.length > 300) records.shift();
    return send(status, body);
  },
};
"""


def index(customers):
    """{service: {key: entry}} or {service: {card: {week: entry}}}, from the customers' services."""
    out = {s: dict() for s in SERVICES}
    sample = dict()
    for c in customers:
        for service, entry in c["services"].items():
            if service not in SERVICES:
                raise SystemExit(f"unknown service in data: {service}")
            if SERVICES[service][0] == ["customerNo"]:
                table = {str(c["customerNo"]).strip(): entry}
            else:
                table = {str(k).strip(): v for k, v in entry.items()}
            for k, v in table.items():
                if k in out[service] and out[service][k] != v:
                    raise SystemExit(f"two different answers for {service} {k}")
                out[service][k] = v
            if service not in sample:
                first = entry if "http" in entry else next(iter(entry.values()))
                first = first if "http" in first else next(iter(first.values()))
                sample[service] = first
    out["__sample__"] = sample
    return out


def schema_of(value):
    if isinstance(value, bool):
        return {"type": "boolean"}
    if isinstance(value, (int, float)):
        return {"type": "number"}
    if isinstance(value, dict):
        return {"type": "object", "properties": {k: schema_of(v) for k, v in value.items()}}
    if isinstance(value, list):
        return {"type": "array", "items": schema_of(value[0]) if value else {}}
    return {"type": "string"}


def openapi(data, base_url):
    string = {"type": "string"}
    fields = {
        "cards.list": ({"customerNo": dict(string, description="The customer number of the call."),
                        "aiFlow": dict(string, enum=["CardOps"])}, ["customerNo", "aiFlow"],
                       "The customer's cards the assistant may talk about."),
        "cards.balance": ({"cardNumber": dict(string, description="cardNumber exactly as cards_list returned it.")},
                          ["cardNumber"], "Statement and due dates, debt per currency, for one card."),
        "statement.week.get": ({"cardNumber": dict(string, description="cardNumber exactly as cards_list returned it.")},
                               ["cardNumber"], "The card's current statement week and day, joint statement info."),
        "statement.week.decide": ({"cardNumber": dict(string, description="cardNumber exactly as cards_list returned it."),
                                   "newStatementWeek": dict(string, enum=["1", "2", "3", "4"]),
                                   "statementDay": dict(string, description="The card's current statementDay from statement_week_get.")},
                                  ["cardNumber", "newStatementWeek", "statementDay"],
                                  "Preview: the dates the card would get with the requested week. Changes nothing."),
        "statement.week.change": ({"cardNumber": dict(string, description="cardNumber exactly as cards_list returned it."),
                                   "newStatementWeek": dict(string, enum=["1", "2", "3", "4"]),
                                   "statementDay": dict(string, description="The card's current statementDay from statement_week_get.")},
                                  ["cardNumber", "newStatementWeek", "statementDay"],
                                  "Changes the card's statement week. Only after the caller agreed to the previewed dates."),
        "contact.email.get": ({"customerNo": dict(string, description="The customer number of the call."),
                               "intAddressInfoType": dict(string, enum=["E", "P", "B"])},
                              ["customerNo", "intAddressInfoType"], "Registered e-mail / phone of the customer."),
        "statement.pdf.send": ({"customerNo": dict(string, description="The customer number of the call."),
                                "cardNumber": dict(string, description="cardNumber exactly as cards_list returned it."),
                                "currencyType": dict(string, enum=["TL", "USD", "EUR", "GBP"]),
                                "statementDate": dict(string, description="statementDate from cards_balance, dd.MM.yyyy."),
                                "emailAddress": dict(string, description="The registered address (ibanEmail of contact_email_get).")},
                               ["customerNo", "cardNumber", "currencyType", "statementDate", "emailAddress"],
                               "Sends the issued statement PDF by e-mail."),
    }
    paths = dict()
    for service, (props, required, summary) in fields.items():
        sample = data["__sample__"][service]["response"]
        ok_schema = schema_of(sample)
        not_found = SERVICES[service][1]
        responses = {"200": {"description": "Success: result.returnCode \"1\".",
                             "content": {"application/json": {"schema": ok_schema}}},
                     "400": {"description": "INVALID_ARGUMENTS_ERROR: a required field is missing or empty. Only result, no data."},
                     "500": {"description": "FBE00099: technical error on the bank's side. Only result, no data."}}
        if not_found:
            responses["404"] = {"description": f"{not_found[0]} (WARNING): {not_found[1]} Only result, no data."}
        paths["/" + service] = {"post": {
            "operationId": service.replace(".", "_"), "summary": summary,
            "requestBody": {"required": True, "content": {"application/json": {"schema": {
                "type": "object", "required": ["data"],
                "properties": {"data": {"type": "object", "required": required, "properties": props},
                               "call": {"type": "object", "properties": {"ani": string,
                                                                          "lang": dict(string, enum=["tr"])}}}}}}},
            "responses": responses}}
    return {"openapi": "3.0.3", "info": {"title": "Freya Bank voice statement services (team mock)", "version": "1"},
            "servers": [{"url": base_url.rstrip("/") + "/voice/v1"}], "paths": paths}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("case")
    ap.add_argument("--out", default=str(pathlib.Path(__file__).resolve().parent / "case"))
    ap.add_argument("--name", default="freya-bank-mock")
    ap.add_argument("--base-url", default="https://freya-bank-mock.example.workers.dev")
    a = ap.parse_args(argv)
    customers = json.loads((pathlib.Path(a.case) / "test-environment" / "test-customers.json")
                           .read_text(encoding="utf-8"))["customers"]
    data = index(customers)
    services = {s: {"lookup": v[0], "notFound": list(v[1]) if v[1] else None, "required": v[2]}
                for s, v in SERVICES.items()}
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    worker = (WORKER.replace("__SERVICES__", json.dumps(services, ensure_ascii=False))
              .replace("__DATA__", json.dumps(data, ensure_ascii=False, separators=(",", ":"))))
    (out / "worker.js").write_text(worker, encoding="utf-8")
    (out / "wrangler.toml").write_text(f'name = "{a.name}"\nmain = "worker.js"\ncompatibility_date = "2025-01-01"\n',
                                       encoding="utf-8")
    (out / "openapi.json").write_text(json.dumps(openapi(data, a.base_url), ensure_ascii=False, indent=1),
                                      encoding="utf-8")
    print(f"{len(customers)} customers -> {out / 'worker.js'} ({(out / 'worker.js').stat().st_size} bytes), "
          f"openapi.json, wrangler.toml")


if __name__ == "__main__":
    main()
